# If dan Else Statement

# 1. if nya
# 2. kondisinya
# 3. aksinya

nama = input('Siapa nama anda? ')

# program sebelumnya
# if kondisi: aksi
# program selanjutnya

# 1. program if inline
if nama=="ucup" : print('Kamu Jelek abieeezzzz!!')
print(f"Terima kasih {nama}")

# 2. program if indentation
if nama=="ucup":
    print("kamu jelek abiez!")
    print("kamu juga jelek banget")
print(f"Terima kasih {nama}")

# 3. Else Statement
if nama=="octopus":
    print("hai octo, si keren!")
else:
    print("Ah kamu bukan octo, kamu tidak keren!")

print("akhir dari program")

