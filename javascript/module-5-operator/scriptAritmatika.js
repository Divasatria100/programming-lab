/* Operator Aritmatika */

// Penjumlahan
let a = 10;
let b = 5;
let sum = a + b; // 15
console.log("Penjumlahan:", sum);

// Pengurangan
let c = 20;
let d = 8;
let diff = c - d; // 12
console.log("Pengurangan:", diff);

// Perkalian
let e = 3
let f = 4;
let product = e * f; // 12
console.log("Perkalian:", product);

// Pembagian
let g = 15;
let h = 3;
let quo = g / h; // 5
console.log("Pembagian:", quo);

// Modulus
let i = 10;
let j = 3;
let mod = i % j; // 1
console.log("Modulus:", mod);

// Eksponen
let k = 2;
let l = 3;
let exp = k ** l; // 8
console.log("Eksponen:", exp);

// Increment
let m = 5;
m++; // m sekarang 6
console.log("Increment:", m);

// Decrement
let n = 10;
n--; // n sekarang 9
console.log("Decrement:", n);

// Penjelasan:
// - Operator aritmatika digunakan untuk melakukan operasi matematika pada angka.
// - Penjumlahan (+), pengurangan (-), perkalian (*), pembagian (/), modulus (%), dan eksponen (**) adalah operator aritmatika dasar.
